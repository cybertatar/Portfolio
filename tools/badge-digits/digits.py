"""Outlines of the figures 0–9 in Golos Text SemiBold for the numbered badges on the PSB home
screen (Annotated.astro). As text, each figure sat a little differently in the badge from one
browser to the next (the font's line metrics); as a path it can be centred on its own bounds.

Font: Google Fonts, Golos Text 600, subset to the figures:
  https://fonts.googleapis.com/css2?family=Golos+Text:wght@600&text=0123456789
Run: python3 tools/badge-digits/digits.py <font.woff2> > src/content/badge-digits.ts
"""

import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1])
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()

print("// Generated by tools/badge-digits/digits.py: Golos Text SemiBold figures as paths,")
print("// each moved so its own bounds start at 0, 0 (font units, y down). Do not edit.")
print("export const badgeDigits: Record<string, { w: number; h: number; d: string }> = {")
for ch in "0123456789":
    glyph = glyphs[cmap[ord(ch)]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(pen, (1, 0, 0, -1, -x0, y1)))
    print(f"  '{ch}': {{ w: {x1 - x0}, h: {y1 - y0}, d: '{pen.getCommands()}' }},")
print("};")
